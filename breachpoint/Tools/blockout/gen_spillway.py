def _base(sign, name):
    """Authored in WEST coordinates; sign=-1 is the 180-degree rotation about Z."""
    F = "Spillway/20_Base_%s" % name

    def rect(x0, y0, x1, y1):
        a, b = sorted((sign * x0, sign * x1))
        c, d = sorted((sign * y0, sign * y1))
        return a, c, b, d

    a, c, b, d = rect(-4400, -2000, -3000, 2000)
    deck(a, c, b, d, T1, "SPW_%s_Roof" % name, F)
    a, c, b, d = rect(-4390, -1900, -4300, 1900)
    box(a, c, T0, b, d, T1 - DECK_T, MAT_TEAM, "SPW_%s_Backsplash" % name, F)

    # x = -3100 and not -3050: the shaft mouth reaches x = -3000, and a pillar clipping
