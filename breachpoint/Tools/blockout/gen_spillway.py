# ---------------------------------------------------------------------------
# Primitives. Every helper takes a world-space AABB and emits one actor.
# ---------------------------------------------------------------------------
def _push(rec):
    _elements.append(rec)
    return rec


def box(x0, y0, z0, x1, y1, z1, mat, label, folder):
    """An axis-aligned solid. SM_Cube's pivot is its min corner, so this is exact."""
    assert x1 > x0 and y1 > y0 and z1 > z0, "degenerate box %s" % label
    return _push({
        "kind": "box", "label": label, "folder": folder,
        "mesh": CUBE, "material": mat,
        "loc": [round(x0, 2), round(y0, 2), round(z0, 2)],
        "rot": [0.0, 0.0, 0.0],
        "scale": [round((x1 - x0) / 100.0, 6),
                  round((y1 - y0) / 100.0, 6),
                  round((z1 - z0) / 100.0, 6)],
        "aabb": [x0, y0, z0, x1, y1, z1],
    })


def deck(x0, y0, x1, y1, top, label, folder, mat=MAT_DECK, thick=DECK_T):
    """A walking surface whose TOP face lands exactly on `top`."""
    return box(x0, y0, top - thick, x1, y1, top, mat, label, folder)


def wall(x0, y0, x1, y1, z0, z1, label, folder, mat=MAT_WALL):
    return box(x0, y0, z0, x1, y1, z1, mat, label, folder)


def slab_with_holes(x0, y0, x1, y1, top, holes, label, folder,
                    mat=MAT_DECK, thick=DECK_T):
    """A deck with rectangular voids cut out of it - the shafts down to the culvert.

    Decomposes the rectangle on every hole edge, drops the cells that fall inside a hole,
    and merges what is left into horizontal runs, so the slab stays a handful of actors
    rather than a grid of hundreds.
    """
    xs = sorted({x0, x1} | {v for h in holes for v in (h[0], h[2]) if x0 < v < x1})
    ys = sorted({y0, y1} | {v for h in holes for v in (h[1], h[3]) if y0 < v < y1})
    n = 0
    for j in range(len(ys) - 1):
        run = None
        for i in range(len(xs) - 1):
            cx, cy = (xs[i] + xs[i + 1]) / 2.0, (ys[j] + ys[j + 1]) / 2.0
            void = any(h[0] < cx < h[2] and h[1] < cy < h[3] for h in holes)
            if not void:
                run = xs[i] if run is None else run
            elif run is not None:
                box(run, ys[j], top - thick, xs[i], ys[j + 1], top, mat,
                    "%s_%02d" % (label, n), folder)
                n += 1
                run = None
        if run is not None:
            box(run, ys[j], top - thick, xs[-1], ys[j + 1], top, mat,
                "%s_%02d" % (label, n), folder)
            n += 1
    return n


def ramp(x0, y0, x1, y1, base, rise, up, label, folder, mat=MAT_TEAM):
    """A walkable ramp filling the AABB, rising toward `up` in {'+X','-X','+Y','-Y'}.

    SM_Ramp is high at local y=0 and low at local y=+run, so the yaw and the pivot corner
    are chosen per direction. Derived once, verified by trace_world.
    """
    w_x, w_y = x1 - x0, y1 - y0
    if up == "-Y":                       # high edge at y0
        yaw, loc, scale, run = 0.0, (x0, y0, base), (w_x, w_y, rise), w_y
    elif up == "+Y":                     # high edge at y1
        yaw, loc, scale, run = 180.0, (x1, y1, base), (w_x, w_y, rise), w_y
    elif up == "+X":                     # high edge at x1
        yaw, loc, scale, run = 90.0, (x1, y0, base), (w_y, w_x, rise), w_x
    elif up == "-X":                     # high edge at x0
        yaw, loc, scale, run = -90.0, (x0, y1, base), (w_y, w_x, rise), w_x
    else:
        raise ValueError("up must be +X/-X/+Y/-Y, got %r" % up)

    slope = math.degrees(math.atan2(rise, run))
    assert slope <= 30.0, "%s is %.1f deg - too steep" % (label, slope)
    return _push({
        "kind": "ramp", "label": label, "folder": folder,
        "mesh": RAMP, "material": mat,
        "loc": [round(v, 2) for v in loc],
        "rot": [0.0, yaw, 0.0],
        "scale": [round(scale[0] / 100.0, 6), round(scale[1] / 100.0, 6),
                  round(scale[2] / 100.0, 6)],
        "aabb": [x0, y0, base, x1, y1, base + rise],
        "slope_deg": round(slope, 2), "up": up,
        "width_uu": w_y if up in ("+X", "-X") else w_x,
    })


def pillar(cx, cy, z0, z1, dia, label, folder, mat=MAT_WALL):
    return _push({
        "kind": "pillar", "label": label, "folder": folder,
        "mesh": CYL, "material": mat,
        "loc": [round(cx, 2), round(cy, 2), round(z0, 2)],
        "rot": [0.0, 0.0, 0.0],
        "scale": [round(dia / 100.0, 6), round(dia / 100.0, 6),
                  round((z1 - z0) / 100.0, 6)],
        "aabb": [cx - dia / 2, cy - dia / 2, z0, cx + dia / 2, cy + dia / 2, z1],
    })


def crate(cx, cy, z0, size, label, folder, mat=MAT_TEAM):
    """Chamfered block - reads as a prop, not architecture. Pivot is the centre."""
    return _push({
        "kind": "crate", "label": label, "folder": folder,
        "mesh": CHAMFER, "material": mat,
        "loc": [round(cx, 2), round(cy, 2), round(z0 + size / 2.0, 2)],
        "rot": [0.0, 0.0, 0.0],
        "scale": [round(size / 100.0, 6)] * 3,
        "aabb": [cx - size / 2, cy - size / 2, z0, cx + size / 2, cy + size / 2, z0 + size],
    })


def crate_if_clear(cx, cy, z0, size, label, folder, mat=MAT_TEAM):
    """A crate, but only if nothing is already there.

    Loose props were hand-placed for three revisions and every layout change started a
    round of whack-a-mole with the overlap gate. The generator checks for itself now: a
    crate that would clash, or that would stand on a shaft mouth, is simply not placed,
    and the summary says how many were dropped. Cover density is a nice-to-have; a crate
    fused into a ramp is a defect.
    """
    h = size / 2.0
    box_ = (cx - h, cy - h, z0, cx + h, cy + h, z0 + size)
    for e in _elements:
        ax0, ay0, az0, ax1, ay1, az1 = e["aabb"]
        if (min(box_[3], ax1) - max(box_[0], ax0) > 1.0
                and min(box_[4], ay1) - max(box_[1], ay0) > 1.0
                and min(box_[5], az1) - max(box_[2], az0) > 1.0):
            _dropped.append(label)
            return None
    for _, sx0, sy0, sx1, sy1, _u in SHAFTS:
        if (min(box_[3], sx1) - max(box_[0], sx0) > 1.0
                and min(box_[4], sy1) - max(box_[1], sy0) > 1.0
                and box_[5] > T0 >= box_[2] - 1.0):
            _dropped.append(label)
            return None
    return crate(cx, cy, z0, size, label, folder, mat)


