def build_culvert():
    F = "Spillway/05_Culvert"
    for nm, x0, y0, x1, y1 in CULVERT_ROOMS:
        deck(x0, y0, x1, y1, TB, "SPW_Culvert_%s" % nm, F)
    for i, (x0, y0, x1, y1) in enumerate(CULVERT_WALLS):
        wall(x0, y0, x1, y1, TB, T0 - FLOOR_T, "SPW_Culvert_Wall_%02d" % i, F)
    for cx, cy in ((-900, -900), (900, -900), (-900, 900), (900, 900)):
        pillar(cx, cy, TB, T0 - FLOOR_T, 180, "SPW_Culvert_Pier_%d_%d" % (cx, cy), F)
    for i, (cx, cy) in enumerate(((400, -1100), (-400, 1100), (-1800, 0), (1800, 0))):
        crate_if_clear(cx, cy, TB, 240, "SPW_Culvert_Crate_%d" % i, F)
    for i, (x0, y0, x1, y1) in enumerate(((-1200, -200, -500, -80),
                                          (500, 80, 1200, 200))):
        box(x0, y0, TB, x1, y1, TB + COVER_H, MAT_WALL, "SPW_Culvert_Cover_%d" % i, F)
    for nm, x0, y0, x1, y1, up in SHAFTS:
        _ground_holes.append((x0, y0, x1, y1))
        ramp(x0, y0, x1, y1, TB, -TB, up, "SPW_%s_Ramp" % nm, F)


