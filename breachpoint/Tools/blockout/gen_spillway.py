def build_tower():
    F = "Spillway/10_Tower"

    # The core was a 12 x 12 m solid cube - the worst of the "big square with nothing on
    # it" the founder called out. It is now a room you fight inside, with the shaft to the
    # culvert in its floor, so the tower is entered at five levels instead of four. Its
    # east and west faces stay solid, which is what kills the cross-map sightline; the
    # doorways face north and south, along the axis that was never the problem.
    D = 250.0                       # half-width of each doorway -> 5 m clear
    wall(-CORE, -CORE, -D, -CORE + 100, T0, T1 - DECK_T, "SPW_Core_S_a", F)
    wall(D, -CORE, CORE, -CORE + 100, T0, T1 - DECK_T, "SPW_Core_S_b", F)
    wall(-CORE, CORE - 100, -D, CORE, T0, T1 - DECK_T, "SPW_Core_N_a", F)
    wall(D, CORE - 100, CORE, CORE, T0, T1 - DECK_T, "SPW_Core_N_b", F)
    wall(-CORE, -CORE + 100, -CORE + 100, CORE - 100, T0, T1 - DECK_T, "SPW_Core_W", F)
    wall(CORE - 100, -CORE + 100, CORE, CORE - 100, T0, T1 - DECK_T, "SPW_Core_E", F)

    # Two opposite quadrants stay solid - their top IS the tier-1 deck, so they carry a
    # path rather than being dead mass. The other two are colonnade.
    for sx, sy, nm in ((-1, -1, "SW"), (1, 1, "NE")):
        x0, x1 = sorted((sx * TW, sx * CORE))
        y0, y1 = sorted((sy * TW, sy * CORE))
        box(x0, y0, T0, x1, y1, T1 - DECK_T, MAT_WALL, "SPW_Tower_Corner_%s" % nm, F)
    for cx, cy in ((1050, -1050), (350, -1250), (-350, -1250),
                   (-1050, 1050), (350, 1250), (-350, 1250)):
        pillar(cx, cy, T0, T1 - DECK_T, 170, "SPW_Tower_Col_%d_%d" % (cx, cy), F)

    deck(-TW, -TW, TW, TW, T1, "SPW_Tower_Deck_T1", F)
    box(-CORE, -CORE, T1, CORE, CORE, T2 - DECK_T, MAT_WALL, "SPW_Tower_Core_T1", F)
    box(-TW, -TW, T1, -300, -1000, T2 - DECK_T, MAT_WALL, "SPW_Tower_Mass_S", F)
    box(300, 1000, T1, TW, TW, T2 - DECK_T, MAT_WALL, "SPW_Tower_Mass_N", F)

    ramp(-TW, -700, -TW + RAMP_W, 100, T1, T1, "+Y", "SPW_Tower_Ramp_T1_T2", F)
    deck(-TW, 100, TW, TW, T2, "SPW_Tower_Deck_T2", F)
    ramp(TW - RAMP_W, 0, TW, 800, T2, T1, "-Y", "SPW_Tower_Ramp_T2_T3", F)
    deck(-1200, -1200, 1200, 0, T3, "SPW_Tower_Crown", F)
    for cx in (-1100, -400, 400, 1100):
        pillar(cx, -900, T1, T3 - DECK_T, 150, "SPW_Tower_Pillar_%d" % cx, F)

    P = 40.0
    wall(-1200, -1200, 1200, -1200 + P, T3, T3 + COVER_H, "SPW_Crown_Parapet_S", F, MAT_TEAM)
    wall(-1200, -1200, -1200 + P, 0, T3, T3 + COVER_H, "SPW_Crown_Parapet_W", F, MAT_TEAM)
    wall(1200 - P, -1200, 1200, 0, T3, T3 + COVER_H, "SPW_Crown_Parapet_E", F, MAT_TEAM)
    box(-150, -600, T3, 150, -300, T3 + 40, MAT_TEAM, "SPW_Crown_Plinth", F)
    box(-1000, -1000, T3, -500, -500, MAST_TOP, MAT_WALL, "SPW_Crown_Mast", F)

    ramp(-2200, 400, -TW, 1000, T0, T1, "+X", "SPW_Tower_Ramp_W", F)
    ramp(TW, -1000, 2200, -400, T0, T1, "-X", "SPW_Tower_Ramp_E", F)


